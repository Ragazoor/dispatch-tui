//! The keybinding table itself, and the row constructors it is written with.

use super::{KeyBinding, KeyContext, KeyNamespace, ANY_OTHER_KEY};

use KeyContext as C;
use KeyNamespace as N;

pub(super) const fn row(
    namespace: KeyNamespace,
    keys: &'static [&'static str],
    context: Option<KeyContext>,
    action: &'static str,
    description: &'static str,
    note: Option<&'static str>,
) -> KeyBinding {
    KeyBinding {
        namespace,
        keys,
        context,
        action,
        description,
        note,
        records_usage: true,
    }
}

/// A row that runs its action but records no usage (text editing).
const fn unrecorded(
    namespace: KeyNamespace,
    keys: &'static [&'static str],
    action: &'static str,
    description: &'static str,
) -> KeyBinding {
    KeyBinding {
        namespace,
        keys,
        context: None,
        action,
        description,
        note: None,
        records_usage: false,
    }
}

const fn r(
    namespace: KeyNamespace,
    keys: &'static [&'static str],
    action: &'static str,
    description: &'static str,
) -> KeyBinding {
    row(namespace, keys, None, action, description, None)
}

const fn normal(
    keys: &'static [&'static str],
    context: Option<KeyContext>,
    action: &'static str,
    description: &'static str,
) -> KeyBinding {
    row(N::BoardNormal, keys, context, action, description, None)
}

