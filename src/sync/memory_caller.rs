    /// The failure mode this once guarded against — a variant added to
    /// `ReducerDomain` but omitted from `ReducerDomain::ALL`, silently
    /// leaving `TOTAL_DOMAINS` (and so `is_complete`) one short — is now
    /// impossible by construction: `reducer_domains!` generates the enum and
    /// `ALL` from the same variant list in one invocation, so there is no
    /// second list for the two to drift apart from. What this match still
    /// catches: forgetting to add a new domain's arm to THIS test — it must
    /// name every variant of `ReducerDomain` to compile, so an added
    /// variant left unhandled here fails the build too.
    #[test]
    fn every_reducer_domain_is_listed_in_all() {
        assert_eq!(ReducerDomain::ALL.len(), TOTAL_DOMAINS);
        for &domain in ReducerDomain::ALL {
            match domain {
                ReducerDomain::TasksAndEpics
                | ReducerDomain::RepoConfig
                | ReducerDomain::Subscriptions
                | ReducerDomain::Settings
                | ReducerDomain::Learnings
                | ReducerDomain::Usage
                | ReducerDomain::AgentState => {}
            }
        }
    }
